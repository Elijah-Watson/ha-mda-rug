def test_configuration_firmware_and_unknown_commands_are_rejected(protocol, payload):
    with pytest.raises(ValueError):
        protocol.frame(bytes.fromhex(payload), 0)


@pytest.mark.parametrize("value", [-1, 0, 101, 255, True, 1.2])
def test_brightness_bounds(protocol, value):
    with pytest.raises(ValueError):
        protocol.color(0, 100, value)


def test_odd_hue_preserves_low_bit(protocol):
    payload = protocol.color(121, 50, 25)
    packed = int.from_bytes(payload[2:4], "big")
    assert packed >> 7 == 121
    assert packed & 127 == 50


@pytest.mark.parametrize("requested,wire", [(0, 240), (120, 120), (240, 0), (60, 180)])
def test_calibrated_red_blue_swap(protocol, requested, wire):
    payload = protocol.color(requested, 80, 30, "BGR")
    assert int.from_bytes(payload[2:4], "big") == (wire << 7) | 80
    assert payload[4] == 30
    protocol.validate_payload(payload)


@pytest.mark.parametrize("hue,saturation", [(17, 0.3), (61, 0.5), (181, 0.8), (299, 1.0)])
def test_hue_correction_matches_independent_rgb_swap(protocol, hue, saturation):
    red, green, blue = colorsys.hsv_to_rgb(hue / 360, saturation, 0.6)
    expected_hue, expected_sat, expected_value = colorsys.rgb_to_hsv(blue, green, red)
    assert protocol.mapped_hue(hue, "BGR") == pytest.approx(expected_hue * 360)
    assert expected_sat == pytest.approx(saturation)
    assert expected_value == pytest.approx(0.6)


@pytest.mark.parametrize("name", ["Game", "Party", "Northern Lights"])
def test_scene_correction_preserves_mode_speed_and_intensity(protocol, name):
    original = protocol.scene(name, 35)
    corrected = protocol.scene(name, 35, "BGR")
    assert original[:15] == corrected[:15]
    for offset in range(15, len(original), 4):
        before = int.from_bytes(original[offset + 1 : offset + 3], "big")
        after = int.from_bytes(corrected[offset + 1 : offset + 3], "big")
        assert after >> 7 == (240 - (before >> 7)) % 360
        assert after & 127 == before & 127
        assert original[offset + 3] == corrected[offset + 3]
    protocol.validate_payload(corrected)


@pytest.mark.parametrize("name", ["Game", "Party", "Northern Lights"])
def test_scene_dimming_changes_only_palette_intensity(protocol, name):
    full = protocol.scene(name, 30, "BGR", 100)
    dim = protocol.scene(name, 30, "BGR", 10)
    for index, value in enumerate(dim):
        if index >= 18 and (index - 18) % 4 == 0:
            assert value == max(1, round(full[index] * 0.1))
        else:
            assert value == full[index]
    protocol.validate_payload(dim)
    corrupted = bytearray(dim)
    corrupted[3] = 1  # Do not allow changing the scene's controller/header fields.
    with pytest.raises(ValueError):
        protocol.validate_payload(bytes(corrupted))


def test_discovery_checks_product_mac_and_profile(protocol):
    data = bytes.fromhex("8007aabbccddeeff00ad220a010d")
    assert protocol.matches({protocol.SERVICE_DATA_UUID: data}, "AA:BB:CC:DD:EE:FF")
    assert not protocol.matches({protocol.SERVICE_DATA_UUID: data}, "AA:BB:CC:DD:EE:FE")
    wrong = data[:8] + b"\x00\xae" + data[10:]
    assert not protocol.matches({protocol.SERVICE_DATA_UUID: wrong}, "AA:BB:CC:DD:EE:FF")


def test_all_supported_lighting_commands_pass_allowlist(protocol):
    payloads = [
        protocol.query(),
        protocol.power(True),
        protocol.power(False),
        protocol.color(359, 67, 1),
    ]
    payloads += [protocol.scene(name, 100) for name in protocol.SCENES]
    for payload in payloads:
        assert protocol.frame(payload, 255)[8:] == payload


